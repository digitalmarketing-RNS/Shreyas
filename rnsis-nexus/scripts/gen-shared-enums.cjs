#!/usr/bin/env node
/**
 * Generates packages/shared/src/enums.ts from the Prisma schema so the web app and the
 * API share one definition of every enum. Run after editing enums in schema.prisma:
 *   node scripts/gen-shared-enums.cjs
 */
const fs = require('fs');
const path = require('path');

const schema = fs.readFileSync(path.join(__dirname, '../apps/api/prisma/schema.prisma'), 'utf8');
const enumRe = /enum\s+(\w+)\s*\{([^}]*)\}/g;
let out = '// AUTO-GENERATED by scripts/gen-shared-enums.cjs from apps/api/prisma/schema.prisma — do not edit.\n\n';
let m;
while ((m = enumRe.exec(schema))) {
  const name = m[1];
  const values = m[2]
    .split('\n')
    .map((l) => l.replace(/\/\/.*$/, '').trim())
    .filter(Boolean);
  out += `export const ${name} = {\n${values.map((v) => `  ${v}: '${v}',`).join('\n')}\n} as const;\n`;
  out += `export type ${name} = (typeof ${name})[keyof typeof ${name}];\n`;
  out += `export const ${name}Values = Object.values(${name}) as ${name}[];\n\n`;
}
fs.writeFileSync(path.join(__dirname, '../packages/shared/src/enums.ts'), out);
console.log('Wrote packages/shared/src/enums.ts');
